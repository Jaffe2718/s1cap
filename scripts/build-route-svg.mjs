#!/usr/bin/env node
/**
 * Emit standalone SVG files for the route diagram from its single geometry source:
 * `docs/figures/s1cap-technical-route.html` (the hand-authored, arrow-level picture).
 *
 * Why: GitHub strips inline `<svg>` out of Markdown, so a README cannot embed the HTML's SVG directly.
 * A committed `.svg` referenced through `<picture>`/`<img>` renders fine, and generating it here keeps one
 * geometry source instead of a second hand-drawn copy that drifts.
 *
 * Two palettes are emitted so GitHub's light and dark themes each get a readable file
 * (`prefers-color-scheme` picks between them).
 *
 * Usage:
 *   node scripts/build-route-svg.mjs           # (re)write both files
 *   node scripts/build-route-svg.mjs --check   # verify they match the HTML, exit 1 on drift
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const htmlPath = join(root, 'docs', 'figures', 's1cap-technical-route.html');
const lightPath = join(root, 'docs', 'figures', 's1cap-technical-route.light.svg');
const darkPath = join(root, 'docs', 'figures', 's1cap-technical-route.dark.svg');

const html = readFileSync(htmlPath, 'utf8');
const sourceHash = createHash('sha256').update(html).digest('hex').slice(0, 16);

const match = html.match(/<svg[\s\S]*?<\/svg>/);
if (!match) {
  console.error('build-route-svg: no <svg> element found in the HTML');
  process.exit(1);
}
const svg = match[0];

/** Palettes mirror the CSS custom properties of the HTML (light in `:root`, dark in `[data-theme=dark]`). */
const PALETTES = {
  light: {
    panel: '#ffffff',
    line: '#c8d1dd',
    ink: '#171a1f',
    muted: '#5c6675',
    laneBg: '#eef1f6',
    laneLine: '#d5dde8',
    dash: '#8b95a5',
    accent: '#23685a',
  },
  dark: {
    panel: '#161a20',
    line: '#2b323c',
    ink: '#e8ecf2',
    muted: '#99a3b2',
    laneBg: '#141922',
    laneLine: '#262f3b',
    dash: '#7c8698',
    accent: '#6fd3b4',
  },
};

/** The HTML styles these classes from its stylesheet; a standalone SVG has to carry them itself. */
function styleBlock(p) {
  return `<style>
    .lane { fill: ${p.laneBg}; stroke: ${p.laneLine}; stroke-width: 1; stroke-dasharray: 5 4; }
    .lane-label { fill: ${p.muted}; font-size: 11px; letter-spacing: .07em; text-transform: uppercase;
      font-family: ui-sans-serif, system-ui, -apple-system, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; }
    .node rect { fill: ${p.panel}; stroke: ${p.line}; stroke-width: 1.2; }
    .node text { fill: ${p.ink}; font-size: 12.5px; text-anchor: middle;
      font-family: ui-sans-serif, system-ui, -apple-system, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; }
    .node .sub { fill: ${p.muted}; font-size: 10.5px; }
    .edge { fill: none; stroke: ${p.muted}; stroke-width: 1.5; }
    .edge.emphasis { stroke: ${p.accent}; stroke-width: 2.2; }
    .edge.dashed { stroke: ${p.dash}; stroke-dasharray: 6 5; }
    .edge-label { fill: ${p.muted}; font-size: 10.5px;
      font-family: ui-sans-serif, system-ui, -apple-system, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; }
    .edge-label.strong { fill: ${p.accent}; font-weight: 600; }
    .note { fill: ${p.muted}; font-size: 10.5px;
      font-family: ui-sans-serif, system-ui, -apple-system, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; }
  </style>`;
}

function standalone(paletteName) {
  const p = PALETTES[paletteName];
  let out = svg
    .replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" ')
    // markers cannot use CSS custom properties in a standalone file
    .replaceAll('fill="var(--muted)"', `fill="${p.muted}"`)
    .replaceAll('fill="var(--accent)"', `fill="${p.accent}"`)
    // the viewer crops tightly; give the standalone file a little breathing room
    .replace('viewBox="0 0 1040 648"', 'viewBox="0 0 1040 648" width="1040" height="648"')
    .replace(/(<svg[^>]*>)/, `$1\n  ${styleBlock(p)}`);
  const banner =
    `<!-- S1CAP technical route (${paletteName}) - generated by scripts/build-route-svg.mjs\n` +
    `     from docs/figures/s1cap-technical-route.html (source sha256:${sourceHash}); do not edit by hand. -->\n`;
  return banner + out + '\n';
}

const outputs = [
  [lightPath, standalone('light')],
  [darkPath, standalone('dark')],
];

if (process.argv.includes('--check')) {
  let bad = 0;
  for (const [path, expected] of outputs) {
    let actual = '';
    try {
      actual = readFileSync(path, 'utf8');
    } catch {
      console.error(`route svg check FAILED: ${relative(root, path)} is missing`);
      bad += 1;
      continue;
    }
    if (actual !== expected) {
      console.error(`route svg check FAILED: ${relative(root, path)} does not match the HTML source`);
      bad += 1;
    }
  }
  if (bad > 0) {
    console.error('run: node scripts/build-route-svg.mjs');
    process.exit(1);
  }
  console.log(`route svg OK: light + dark match the HTML source (sha256:${sourceHash})`);
  process.exit(0);
}

for (const [path, content] of outputs) {
  writeFileSync(path, content, 'utf8');
  console.log(`${relative(root, path).replace(/\\/g, '/')}: ${content.length} bytes (source sha256:${sourceHash})`);
}
